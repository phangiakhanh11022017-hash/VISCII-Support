#pragma once
#include <string>

using vchar = unsigned char;

// Bảng dịch nhanh các mã VISCII (128-255) sang UTF-8 để Console hiển thị được
inline std::string to_utf8(const vchar* s) {
    static const char* map[128] = {
        "Ạ","Ắ","Ằ","Ặ","Ấ","Ầ","Ẩ","Ậ","Ẽ","Ẹ","Ế","Ề","Ể","Ễ","Ệ","Ố",
        "Ồ","Ổ","Ỗ","Ộ","Ợ","Ớ","Ờ","Ở","Ị","Ụ","Ứ","Ừ","Ử","Ỡ","Ữ","Ự",
        "Õ","ắ","ằ","ặ","ấ","ầ","ẩ","ậ","ẽ","ẹ","ế","ề","ể","ễ","ệ","ố",
        "ồ","ổ","ỗ","ỡ","Ơ","ộ","ờ","ở","ị","ự","ứ","ừ","ử","ơ","ớ","Ư",
        "À","Á","Â","Ã","Ả","Ă","Ẳ","Ẵ","È","É","Ê","Ẻ","Ì","Í","Ĩ","Ỳ",
        "Đ","ứ","Ò","Ó","Ô","ạ","ỷ","ừ","ử","Ù","Ú","Ỹ","Ỵ","Ý","ỡ","ư",
        "à","á","â","ã","ả","ă","ữ","ẫ","è","é","ê","ẻ","ì","í","ĩ","ỉ",
        "đ","ự","ò","ó","ô","õ","ỏ","ọ","ụ","ù","ú","ũ","ủ","ý","ợ","ỹ"
    };
    std::string res;
    for (int i = 0; s[i] != 0; ++i) {
        if (s[i] < 128) res += (char)s[i];
        else res += map[s[i] - 128];
    }
    return res;
}
